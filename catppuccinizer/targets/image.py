"""Image target: recolour wallpapers and other pictures.

Methods (core.recolor):
- keys: source colours + intensity over a background; best for flat art (line
  art, logos, neon on a plain background). Supports --map and "accent".
- lut:  a colour look-up table that pulls every colour towards the Catppuccin
  palette in Oklab, keeping part of the original lightness; for photos,
  paintings and soft gradients.
- lutgen: like lut, with a table generated by the external lutgen tool
  (--lutgen-*); only when asked for.
"auto" picks keys when the source colours explain the image well, the
background is plain and the edges are crisp.

SVG / SVGZ files stay vector: the colours written in the file (fill, stroke,
stop-color…) are mapped to Catppuccin roles and replaced, nothing is rasterised.
"""
import shutil
import subprocess
import tempfile
from pathlib import Path

from PIL import Image

from ..core import recolor
from ..core.formats import read_text, recolour_text, write_text
from ..core.mapping import (colour_report, note_accent_ignored, print_colours, text_colours,
                            text_lookup, uses_accent)
from ..core.naming import output_name, planned, slug
from ..core.options import Option
from ..core.parts import accent_sets, check_parts
from ..core.palette import FLAVOR_TITLES
from ..core.sources import wallpaper_sections
from ..core.target import Target

VECTOR = {".svg", ".svgz"}
EXTS = {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".qoi"} | VECTOR


def collect(paths):
    files = []
    for p in map(Path, paths):
        if p.is_dir():
            files += sorted(f for f in p.rglob("*") if f.suffix.lower() in EXTS)
        elif p.is_file():
            files.append(p)
        else:
            raise SystemExit(f"Not found: {p}")
    return files


class ImageTarget(Target):
    name = "image"
    help = "recolour wallpapers and other images"
    default_out = "images"

    def options(self):
        return [Option("images", label="Images", nargs="+", metavar="IMAGE", accept="images",
                       help="image file(s) or folder(s)"),
                *recolor.method_options()]

    def sources(self):
        return wallpaper_sections()

    def colours(self, a):
        files = images(a)
        out = []
        for path in files:
            if path.suffix.lower() in VECTOR:
                out.append(colour_report(path, "vector", vector_colours(path, a), part=part(path)))
            else:
                out.append(recolor.colour_report(path, *recolor.plan(path, a, verbose=False),
                                                 part=part(path)))
        return out

    def outputs(self, a):
        files = images(a)
        out = []
        for path in files:
            if path.suffix.lower() in VECTOR:
                uses = uses_accent(vector_colours(path, a))
                ext = ".png" if a.preview and shutil.which("rsvg-convert") else path.suffix
            else:
                method, grp = recolor.plan(path, a, verbose=False)
                uses = recolor.accent_ignored_reason(method, grp) is None
                ext = ".png" if a.preview else recolor.output_suffix(method, path)
            folder = a.out / "previews" if a.preview else a.out
            out += [planned(folder / f"{output_name(flv, path.stem, name, a.suffix)}{ext}")
                    for flv in a.flavor for _, name in sets_of(a, path, uses)]
        return out

    def build(self, a):
        files = images(a)
        if not files:
            raise SystemExit("No images found")
        a.out.mkdir(parents=True, exist_ok=True)
        for path in files:
            if path.suffix.lower() in VECTOR:
                self.run_vector(path, a)
                continue
            method, grp = recolor.plan(path, a)
            ignored = recolor.accent_ignored_reason(method, grp)
            if ignored:
                note_accent_ignored(a, ignored)
            for flv in a.flavor:
                for _, acc in sets_of(a, path, not ignored):
                    name = output_name(flv, path.stem, acc, a.suffix)
                    im = recolor.render(path, method, grp, flv, acc, a)
                    if a.preview:
                        (a.out / "previews").mkdir(exist_ok=True)
                        dst = a.out / "previews" / f"{name}.png"
                        recolor.side_by_side(path, im, dst, grp if method == "keys" else None)
                    else:
                        dst = recolor.save_image(im, a.out / name, method, path)
                    print(f"  -> {dst}  (Catppuccin {FLAVOR_TITLES[flv]}{' ' + acc if acc else ''})")

    def run_vector(self, path, a):
        colors = vector_colours(path, a)
        print(f"{path.name}: vector ({len(colors)} colours)")
        print_colours(colors, show_share=False)
        text = read_text(path)
        if not uses_accent(colors):
            note_accent_ignored(a)
        for flv in a.flavor:
            for _, acc in sets_of(a, path, uses_accent(colors)):
                lookup = text_lookup(colors, flv, acc)
                name = output_name(flv, path.stem, acc, a.suffix)
                new = recolour_text(text, "svg", lookup)
                if a.preview:
                    (a.out / "previews").mkdir(exist_ok=True)
                    dst = a.out / "previews" / f"{name}.png"
                    if not svg_preview(path, new, dst):
                        dst = dst.with_suffix(path.suffix)
                        write_text(dst, new)
                else:
                    dst = a.out / f"{name}{path.suffix}"
                    write_text(dst, new)
                print(f"  -> {dst}  (Catppuccin {FLAVOR_TITLES[flv]}{' ' + acc if acc else ''})")


def vector_colours(path, a):
    """Colours written in an SVG, mapped to Catppuccin roles, after -m."""
    return text_colours([path], a.map, strict=a.strict_map, group="svg")


def images(a):
    """The image files, their parts checked (-a NAME=ACCENT: one image's accent)."""
    files = collect(a.images)
    a.strict_map = len(files) == 1      # with several images, a name may exist in only some
    check_parts(a, [part(p) for p in files])
    return files


def part(path):
    """The part an image is (core.parts): its file name, as in the output names."""
    return slug(path.stem)


def sets_of(a, path, uses):
    """core.parts.accent_sets of one image (its accent, when it uses one)."""
    return accent_sets(a, [part(path)] if uses else [])


def svg_preview(src, new_text, dst):
    """Before/after PNG of an SVG with rsvg-convert; False when it is not installed."""
    tool = shutil.which("rsvg-convert")
    if not tool:
        print("  (install rsvg-convert, from librsvg, for a PNG preview; writing the SVG instead)")
        return False
    with tempfile.TemporaryDirectory(prefix="catppuccinize-") as tmp:
        tmp = Path(tmp)
        after_svg = tmp / "after.svg"
        after_svg.write_text(new_text)
        before_svg = tmp / "before.svg"
        before_svg.write_text(read_text(src))
        for f in (before_svg, after_svg):
            subprocess.run([tool, "-w", "512", "-o", str(f.with_suffix(".png")), str(f)], check=True)
        with Image.open(tmp / "after.png") as im:
            recolor.side_by_side(tmp / "before.png", im.copy(), dst)
    return True


TARGET = ImageTarget()
