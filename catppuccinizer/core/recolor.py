SEPARATION = Option("--separation", label="Colour separation", type=float, default=DEFAULT_SEPARATION,
                    range=(0, 1), scope="method:keys", when={"method": ["auto", "keys"]},
                    image="options-separation.jpg",
                    help=f"keys: 0 = merge close colours, 1 = keep faint ones apart "
                         f"(default: {DEFAULT_SEPARATION})",
                    explain="How the source colours are found. Higher values keep faint or small "
                            "colours apart (a yellow sun on an orange sky, a thin outline) and, "
                            "above the default, also find colours darker than the background; "
                            "lower values merge close colours into fewer source colours. An "
                            "element that disappears or takes the colour of its neighbour needs a "
                            "higher value, or its colour added with -m '#rrggbb=TARGET'. With "
                            "auto, more colours also rebuild the image better, so keys may be "
                            "picked where lut was.")
# --method when only the LUT methods are offered (the lut target)
LUT_ONLY = {"image": "options-lut.jpg",
            "explain": "lut is the built-in table: every colour is pulled towards the palette "
                       "in Oklab, keeping part of its lightness (--keep-lum) and blending "
                       "neighbouring accents (--smooth). lutgen makes the table with the "
                       "external lutgen tool, with its own interpolation algorithms "
                       "(--lutgen-*): similar results, other trade-offs."}
LUT_OPTIONS = [
    Option("--keep-lum", label="Keep lightness", type=float, default=0.5, range=(0, 1), scope="method:lut",
           when={"method": ["auto", "lut"]}, image="options-keep-lum.jpg",
           help="lut: 0 = palette lightness, 1 = original lightness (default: 0.5)",
           explain="At 0 every colour takes the lightness of the palette's neutrals (crust to "
                   "text): low contrast, very Catppuccin. At 1 the original lightness is kept: "
                   "deep blacks and bright highlights, more contrast."),
    Option("--smooth", label="Accent blending", type=float, default=0.08, metavar="R", scope="method:lut",
           when={"method": ["auto", "lut"]}, image="options-smooth.jpg",
           help="lut: blend radius in Oklab; smaller = purer palette colours (default: 0.08)",
           explain="How far a colour looks for accents. Small values snap each hue to its "
                   "closest accent (distinct bands); large values blend many accents together, "
                   "towards a pastel, almost uniform tint."),
]


def check_method_arguments(a):
    """Fail early on option values the methods cannot use (ranges: core.options.check)."""
    if a.smooth <= 0:
        raise SystemExit("--smooth must be greater than 0")
    if a.method == "lutgen":
        lutgen.options(a)


# ---------------------------------------------------------------------- keys
def recolor_image(path, src_bg, keys, targets, base, quantize=True):
    """Each pixel ~ bg + t * (key - bg): find the key and intensity t that explain
    it best, then rebuild it as base + t * (target - base). Alpha is kept.
    path may be a PIL image; quantize=False keeps opaque results in RGB."""
    px, alpha = load_rgba(path)
    flat = px.reshape(-1, 3) - src_bg
    k = keys - src_bg
    t = np.clip((flat @ k.T) / np.maximum((k ** 2).sum(1), 1e-6), 0, 1)       # (N, K)
    if len(keys) == 1 and alpha is None:
        # single colour: indexed PNG whose palette is the exact base -> target ramp
        idx = np.round(t[:, 0] * 255).astype(np.uint8).reshape(px.shape[:2])
        ramp = np.arange(256, dtype=np.float32)[:, None] / 255
        pal = np.clip(base + ramp * (targets[0] - base) + 0.5, 0, 255).astype(np.uint8)
        im = Image.fromarray(idx, "P")
        im.putpalette(pal.flatten().tolist())
        return im
    if len(keys) == 1:
        best = np.zeros(len(flat), int)
    else:
        best = (((flat[:, None, :] - t[..., None] * k[None]) ** 2).sum(-1)).argmin(1)
    tb = t[np.arange(len(flat)), best][:, None]
    out = np.clip((base + tb * (targets[best] - base)).reshape(px.shape) + 0.5, 0, 255)
    if alpha is not None:
        rgba = np.dstack([out, alpha]).astype(np.uint8)
        return Image.fromarray(rgba, "RGBA")
    im = Image.fromarray(out.astype(np.uint8), "RGB")
    if not quantize:
        return im
    return im.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)


def _recolor_frame(args):
    frame, src_bg, keys, targets, base, quantize = args
    return recolor_image(frame, src_bg, keys, targets, base, quantize)


def recolor_frames(frames, src_bg, keys, targets, base, quantize=True, parallel=True, batch=None):
    """recolor_image over an iterable of PIL frames, in order; in worker processes
    when parallel (worth it for long animations). Frames are read a batch at a
    time, so long animations never sit in memory."""
    if not parallel:
        for fr in frames:
            yield recolor_image(fr, src_bg, keys, targets, base, quantize)
        return
    workers = os.cpu_count() or 1
    batch = batch or workers * 2
    with ProcessPoolExecutor(workers) as pool:
        chunk = []
        for fr in frames:
            chunk.append((fr, src_bg, keys, targets, base, quantize))
            if len(chunk) == batch:
                yield from pool.map(_recolor_frame, chunk)
                chunk = []
        if chunk:
            yield from pool.map(_recolor_frame, chunk)


def recolor_job(args):
    """Pool-friendly: (path, dst, src_bg, keys, targets, base) -> saved image."""
    path, dst, src_bg, keys, targets, base = args
    recolor_image(path, src_bg, keys, targets, base).save(dst, optimize=True)


# ---------------------------------------------------------------- analysis
def analyse(path, separation=DEFAULT_SEPARATION):
    """Detect source colours; return them with the reconstruction error on the
    content pixels and the share of the image covered by the plain background."""
    grp = detect_group([path], is_ui=False, params=detect_params(separation))
    err, bg_share = fit_error(path, grp)
    return grp, err, bg_share, sharpness(path)


def fit_error(path, grp):
    """How well a group's background + source colours rebuild an image: mean error
    (0..255) on the content pixels, and the share covered by the background."""
    im = Image.open(path)
    im.thumbnail((512, 512))
    px = np.asarray(im.convert("RGB"), np.float32).reshape(-1, 3)
    bg = hex2rgb(grp["background"])
    keys = np.array([hex2rgb(c["source"]) for c in grp["colors"].values()]) - bg
    d = px - bg
    t = np.clip((d @ keys.T) / np.maximum((keys ** 2).sum(1), 1e-6), 0, 1)
    recon = t[..., None] * keys[None]
    err = np.abs(d[:, None, :] - recon).mean(-1).min(1)
    content = np.abs(d).max(-1) > 24
    return float(err[content].mean() if content.any() else 0), float(1 - content.mean())


def sharpness(path):
    """99th percentile of the local contrast, relative to the image's range:
    ~0.01-0.03 for blurred blobs and soft gradients, > 0.2 for line art and photos."""
    im = Image.open(path).convert("L")
    im.thumbnail((1024, 1024))
    a = np.asarray(im, np.float32)
    # measure on the content's bounding box: a small logo on a plain background
    # would otherwise leave nothing but background in the percentiles
    border = np.concatenate([a[0], a[-1], a[:, 0], a[:, -1]])
    ys, xs = np.nonzero(np.abs(a - np.median(border)) > 8)
    if len(ys):
        pad = 8
        a = a[max(ys.min() - pad, 0):ys.max() + pad + 1, max(xs.min() - pad, 0):xs.max() + pad + 1]
    if min(a.shape) < 2:
        return 0.0
    g = np.maximum(np.abs(np.diff(a, axis=1))[:-1], np.abs(np.diff(a, axis=0))[:, :-1])
    return float(np.percentile(g, 99) / (np.percentile(a, 99) - np.percentile(a, 1) + 1))


# --------------------------------------------------------------------- LUT
@lru_cache(maxsize=None)
def build_lut(flavor, smooth, keep_lum, n=33):
    """n^3 RGB grid -> Catppuccin, as float32 (n, n, n, 3).

    - lightness: the original lightness is mapped onto the flavour's neutral ramp
      (crust ... text), then blended with the original by keep_lum;
    - colour: the hue goes to a soft mix of the closest accents (in the a/b plane),
      applied in proportion to the original chroma, so grays stay neutral.
    """
    p = PALETTES[flavor]
    neutrals = srgb_to_oklab(np.array([hex2rgb(p[c]) for c in NEUTRALS]))
    neutrals = neutrals[np.argsort(neutrals[:, 0])]
    accents = srgb_to_oklab(np.array([hex2rgb(p[c]) for c in ACCENTS]))
    g = np.linspace(0, 255, n, dtype=np.float32)
    grid = np.stack(np.meshgrid(g, g, g, indexing="ij"), -1).reshape(-1, 3)
    lab = srgb_to_oklab(grid)
    L, ab = lab[:, 0], lab[:, 1:]

    # neutral ramp: original lightness 0..1 spread over [crust, text]
    lo, hi = neutrals[0, 0], neutrals[-1, 0]
    ramp_L = lo + np.clip(L, 0, 1) * (hi - lo)
    neutral = np.stack([np.interp(ramp_L, neutrals[:, 0], neutrals[:, k]) for k in range(3)], -1)

    # accent mix by hue/chroma distance
    d2 = ((ab[:, None, :] - accents[None, :, 1:]) ** 2).sum(-1)
    w = np.exp(-(d2 - d2.min(1, keepdims=True)) / (2 * smooth ** 2))
    acc_ab = (w[..., None] * accents[None, :, 1:]).sum(1) / w.sum(1, keepdims=True)
    # mixing neighbouring accents shortens the a/b vector: restore the accents' chroma
    acc_c = (w * np.linalg.norm(accents[:, 1:], axis=1)[None]).sum(1) / w.sum(1)
    acc_ab *= (acc_c / np.maximum(np.linalg.norm(acc_ab, axis=1), 1e-6))[:, None]
    k = np.clip(np.linalg.norm(ab, axis=1) / CHROMA_REF, 0, 1)[:, None]

    out = np.empty_like(lab)
    out[:, 0] = keep_lum * L + (1 - keep_lum) * neutral[:, 0]
    # darker than the accents -> proportionally less chroma (avoids neon on dark pixels)
    dim = np.clip(out[:, 0] / (0.75 * accents[:, 0].mean()), 0, 1)[:, None]
    out[:, 1:] = (1 - k) * neutral[:, 1:] + k * acc_ab * dim
    return oklab_to_srgb(out).reshape(n, n, n, 3).astype(np.float32)


def lut_for(method, flavor, a, n=33):
    """Cube of a LUT method for a flavour (lutgen: at its own --lutgen-level)."""
    if method == "lutgen":
        return lutgen.build(flavor, lutgen.options(a))
    return build_lut(flavor, a.smooth, a.keep_lum, n)


def recolor_lut(path, cube):
    rgb_arr, alpha = load_rgba(path)
    out = np.clip(apply_lut(rgb_arr, cube) + 0.5, 0, 255)
    if alpha is not None:
        return Image.fromarray(np.dstack([out, alpha]).astype(np.uint8), "RGBA")
    return Image.fromarray(out.astype(np.uint8), "RGB")


# --------------------------------------------------------------------- API
def plan(path, a, verbose=True):
    """Return (method, group config or None) for one image."""
    check_method_arguments(a)
    grp, err, bg_share, sharp = None, None, None, None
    if a.method in ("auto", "keys"):
        grp, err, bg_share, sharp = analyse(path, a.separation)
    flat = (err is not None and err < FIT_THRESHOLD and bg_share >= MIN_BG_SHARE
            and sharp >= MIN_SHARPNESS)
    method = a.method if a.method != "auto" else ("keys" if flat else "lut")
    if method == "keys":
        cfg = {"groups": {"image": grp}}
        apply_maps(cfg, a.map, strict=getattr(a, "strict_map", True))
    elif a.map:
        print(f"  note: --map is ignored by the {method} method ({path.name})")
    if verbose:
        fit = (f" (fit error {err:.1f}, background {bg_share:.0%}, sharpness {sharp:.2f})"
               if err is not None else "")
        print(f"{path.name}: {method}{fit}")
        if method == "keys":
            bg = "transparent" if grp["transparent"] else f"background {grp['background']}"
            print(f"  {bg}")
            print_colours(grp["colors"])
    return method, grp


def render(path, method, grp, flavor, accent, a):
    if method in LUT_METHODS:
        return recolor_lut(path, lut_for(method, flavor, a))
    keys = np.array([hex2rgb(c["source"]) for c in grp["colors"].values()])
    targets = np.array([rgb(flavor, accent if c["target"] == "accent" else c["target"])
                        for c in grp["colors"].values()])
    return recolor_image(path, hex2rgb(grp["background"]), keys, targets, rgb(flavor, "base"))


def colour_report(path, method, grp, note=None):
    """--colours entry of an image after plan(): its colours, or why -m does
    not apply (LUT methods use no source colours)."""
    if method in LUT_METHODS:
        return mapping.colour_report(path, method, note=f"the {method} method uses no source colours")
    return mapping.colour_report(path, method, grp["colors"], background=mapping.background_of(grp),
                                 note=note)


def accent_ignored_reason(method, grp):
    """Why the accent has no effect on an image recoloured with this method, or
    None when it is used."""
    if method in LUT_METHODS:
        return f"by the {method} method"
    return None if uses_accent(grp["colors"]) else NO_ACCENT


def output_suffix(method, src, opaque=None):
    """Extension of a recoloured image: a photo recoloured with a LUT keeps its JPEG /
    WebP format when it is opaque, the rest is PNG. opaque: whether the rendered
    image has no alpha (None: read from the source's header)."""
    ext = Path(src).suffix.lower()
    if method not in LUT_METHODS or ext not in (".jpg", ".jpeg", ".webp"):
        return ".png"
    if opaque is None:
        with Image.open(src) as im:
            opaque = "A" not in im.mode and "transparency" not in im.info
    return ext if opaque else ".png"


def save_image(im, dst, method, src):
    ext = output_suffix(method, src, opaque=im.mode == "RGB")
    if ext != ".png":
        dst = dst.with_suffix(ext)
        im.save(dst, quality=95)
    else:
        dst = dst.with_suffix(".png")
        # optimize: ~5x slower on a 4K picture for files under 1 % smaller
        im.save(dst, optimize=im.width * im.height <= OPTIMIZE_MAX_PIXELS)
    return dst


# ------------------------------------------------------------------ previews
SHEET_GAP, SHEET_GAP_COLOUR = 8, (69, 71, 90)     # between the panels (the GUI's picker finds it)
# well-separated plain colours for the separation panel, one per source colour
SEPARATION_COLOURS = [(230, 25, 75), (60, 180, 75), (255, 225, 25), (0, 130, 200), (245, 130, 48),
                      (145, 30, 180), (70, 240, 240), (240, 50, 230), (210, 245, 60),
                      (250, 190, 212), (0, 128, 128), (220, 190, 255), (170, 110, 40),
                      (255, 250, 200), (128, 0, 0), (170, 255, 195)]


def on_black(im):
    out = Image.new("RGBA", im.size, (0, 0, 0, 255))
    out.alpha_composite(im.convert("RGBA"))
    return out.convert("RGB")


def separation_image(path, grp):
    """What keys sees: each source colour of grp in its own plain colour, as bright
    as the pixel is made of it (t), black for the background. A part of the image
    that has no colour of its own shows in its neighbour's colour, or dark.
    Returns (image, [(name, colour)]) for the legend."""
    names = list(grp["colors"])
    keys = np.array([hex2rgb(c["source"]) for c in grp["colors"].values()])
    cols = np.array([SEPARATION_COLOURS[i % len(SEPARATION_COLOURS)] for i in range(len(keys))],
                    np.float32)
    im = recolor_image(path, hex2rgb(grp["background"]), keys, cols, np.zeros(3, np.float32),
                       quantize=False)
    return on_black(im), [(n, tuple(int(v) for v in c)) for n, c in zip(names, cols)]


def draw_legend(im, items):
    """The names of the separation panel's colours, in its top-left corner."""
    d = ImageDraw.Draw(im, "RGBA")
    font = ImageFont.load_default(size=13)
    lines = [(n, c) for n, c in items]
    w = max(int(d.textlength(n, font=font)) for n, _ in lines) + 30
    d.rectangle((4, 4, 4 + w, 8 + 18 * len(lines)), fill=(0, 0, 0, 170))
    for i, (n, c) in enumerate(lines):
        y = 8 + 18 * i
        d.rectangle((10, y + 2, 20, y + 12), fill=c)
        d.text((26, y), n, fill=(255, 255, 255), font=font)
    return im


def side_by_side(src, im, out, grp=None):
    """before | after, and with a keys group (grp) the separation panel."""
    before = Image.open(src).convert("RGB")
    before.thumbnail((900, 900))
    panels = [before, on_black(im).resize(before.size)]
    if grp is not None:
        sep, legend = separation_image(src, grp)
        panels.append(draw_legend(sep.resize(before.size), legend))
    sheet = Image.new("RGB", (len(panels) * (before.width + SHEET_GAP) - SHEET_GAP, before.height),
                      SHEET_GAP_COLOUR)
    for i, p in enumerate(panels):
        sheet.paste(p, (i * (before.width + SHEET_GAP), 0))
    sheet.save(out)
